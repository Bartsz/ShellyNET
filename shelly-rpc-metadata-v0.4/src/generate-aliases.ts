import fs from 'node:fs';
import path from 'node:path';
import { isMainModule } from './is-main.js';
import { discoverShellyTypes, type ShellyDiscovery } from './discover.js';
import { componentAliasBase, methodAliasBase } from './naming.js';
import { generatedDir, generatedTypesFile } from './paths.js';

function moduleSpecifierForDeclaration(declarationFile: string): string {
  let relative = path.relative(path.dirname(generatedTypesFile), declarationFile);
  relative = relative.replaceAll('\\', '/');

  // TypeScript declaration packages normally contain Foo.d.ts for an import
  // written as Foo.js. Using the .js specifier keeps NodeNext semantics happy
  // while TypeScript resolves it back to Foo.d.ts.
  relative = relative.replace(/\.d\.(?:mts|cts|ts)$/i, (match) => {
    if (match.toLowerCase() === '.d.mts') return '.mjs';
    if (match.toLowerCase() === '.d.cts') return '.cjs';
    return '.js';
  });

  if (!relative.startsWith('.')) {
    relative = `./${relative}`;
  }

  return relative;
}

function renderImports(discovery: ShellyDiscovery): string[] {
  const byFile = new Map<string, Set<string>>();

  const add = (declarationFile: string, typeName: string): void => {
    let names = byFile.get(declarationFile);
    if (!names) {
      names = new Set<string>();
      byFile.set(declarationFile, names);
    }
    names.add(typeName);
  };

  for (const method of discovery.rpcMethods) {
    add(method.declarationFile, method.mapTypeName);
  }

  for (const component of discovery.components) {
    add(component.declarationFile, component.statusTypeName);
    add(component.declarationFile, component.configTypeName);
  }

  const lines: string[] = [];
  for (const [declarationFile, names] of [...byFile.entries()].sort(([a], [b]) =>
    a.localeCompare(b)
  )) {
    const specifier = moduleSpecifierForDeclaration(declarationFile);
    const sortedNames = [...names].sort((a, b) => a.localeCompare(b));

    if (sortedNames.length === 1) {
      lines.push(
        `import type { ${sortedNames[0]} } from ${JSON.stringify(specifier)};`
      );
      continue;
    }

    lines.push('import type {');
    for (const name of sortedNames) {
      lines.push(`  ${name},`);
    }
    lines.push(`} from ${JSON.stringify(specifier)};`);
  }

  return lines;
}

export function renderGeneratedTypes(discovery: ShellyDiscovery): string {
  const lines: string[] = [
    '// <auto-generated />',
    '// Generated from @taulfsime/shelly-rpc-ts. Do not edit manually.',
    '//',
    '// Important: these aliases intentionally reference concrete component',
    '// types and concrete RPC method maps. Do not replace them with the global',
    '// shelly_component_*<T> / shelly_rpc_method_*<K> helpers: schema generators',
    '// can recursively expand their global conditional/Extract<> maps.',
    '',
    ...renderImports(discovery),
    '',
  ];

  for (const method of discovery.rpcMethods) {
    const base = methodAliasBase(method.method);
    const entryType = `${base}_Entry`;
    const indexedMethod = `${method.mapTypeName}[${JSON.stringify(method.method)}]`;

    lines.push(
      `type ${entryType} = ${indexedMethod};`,
      `export type ${base}_Params =`,
      `  ${entryType} extends { params: infer P } ? P :`,
      `  ${entryType} extends { params?: infer P } ? P | undefined :`,
      '  never;',
      `export type ${base}_Result =`,
      `  ${entryType} extends { result: infer R } ? R : unknown;`,
      ''
    );
  }

  for (const component of discovery.components) {
    const base = componentAliasBase(component.component);
    lines.push(
      `export type ${base}_Status = ${component.statusTypeName};`,
      `export type ${base}_Config = ${component.configTypeName};`,
      ''
    );
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

export function generateAliases(
  discovery: ShellyDiscovery = discoverShellyTypes()
): ShellyDiscovery {
  fs.mkdirSync(generatedDir, { recursive: true });
  fs.writeFileSync(generatedTypesFile, renderGeneratedTypes(discovery), 'utf8');

  console.log(
    `Generated ${generatedTypesFile} (${discovery.methods.length} RPC methods, ${discovery.componentTypes.length} component types).`
  );

  return discovery;
}

if (isMainModule(import.meta.url)) {
  generateAliases();
}
